def catalog_rows() -> List[Dict[str, object]]:
    rows = []
    for sector, rules in SUBSECTOR_RULES.items():
        for index, (name, _keywords) in enumerate(rules):
            rows.append({
                "subsector_code": name,
                "sector_code": sector,
                "name": name,
                "sort_order": index,
            })
    return rows


def assign_subsector(name: str, sector: Optional[str]) -> Optional[str]:
    """在所属大类内按具体到宽泛匹配，命中即停。"""
    rules = SUBSECTOR_RULES.get(sector or "")
    if not rules or not name:
        return None
    for label, keywords in rules:
        if _matches(name, label, keywords):
            return label
    return None


def _matches(name: str, label: str, keywords: Sequence[str]) -> bool:
    if label == "超大盘(300/50)" and any(token in name for token in ("科创", "创业板", "双创")):
        return False
    return any(keyword in name for keyword in keywords)
